const xliffPath = path.join(workspaceRoot, 'apps/landing/src/locale/messages.xlf');
const src = readFileSync(xliffPath, 'utf8');

const unitRe = /<trans-unit id="([^"]+)"[^>]*>([\s\S]*?)<\/trans-unit>/g;
const missing = [];
const out = src
  .replace('<file source-language="ru"', '<file source-language="ru" target-language="kk-KZ"')
  .replace(unitRe, (whole, id, inner) => {
    const target = translations[id];
    if (target === undefined) {
      missing.push(id);
      return whole;
    }
    const sourceMatch = inner.match(/<source>[\s\S]*?<\/source>/);
    return whole.replace(
      sourceMatch[0],
      `${sourceMatch[0]}\n        <target>${target}</target>`
    );
  });

if (missing.length) {
  console.error('Missing translations for:', missing.join(', '));
  process.exit(1);
}

writeFileSync(path.join(workspaceRoot, 'apps/landing/src/locale/messages.kk-KZ.xlf'), out);
console.log('Wrote messages.kk-KZ.xlf with', Object.keys(translations).length, 'translations');
