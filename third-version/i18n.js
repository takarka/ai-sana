let currentLanguage = 'ru';

function initI18n() {
  const savedLang = localStorage.getItem('pisa_lang');
  if (savedLang && (savedLang === 'ru' || savedLang === 'kz')) {
    currentLanguage = savedLang;
  }
  applyTranslations();
}

function setLanguage(lang) {
  if (lang !== 'ru' && lang !== 'kz') return;
  currentLanguage = lang;
  localStorage.setItem('pisa_lang', lang);
  document.documentElement.setAttribute('lang', lang);
  applyTranslations();

  // Update button active state
  document.querySelectorAll('.lang-btn').forEach(btn => {
    btn.classList.toggle('active', btn.getAttribute('data-lang') === lang);
  });

  // Notify custom listeners (e.g. WebGL tooltip refresh)
  window.dispatchEvent(new CustomEvent('languageChanged', { detail: { lang } }));
}

function getCurrentLang() {
  return currentLanguage;
}

function t(key) {
  const dict = translations[currentLanguage] || translations.ru;
  return dict[key] || key;
}

function applyTranslations() {
  const elements = document.querySelectorAll('[data-i18n]');
  elements.forEach(el => {
    const key = el.getAttribute('data-i18n');
    const translation = t(key);
    if (translation && translation !== key) {
      if (translation.includes('<span') || translation.includes('<strong>')) {
        el.innerHTML = translation;
      } else {
        el.textContent = translation;
      }
    }
  });

  // Update inputs with data-i18n-placeholder
  const inputs = document.querySelectorAll('[data-i18n-placeholder]');
  inputs.forEach(inp => {
    const key = inp.getAttribute('data-i18n-placeholder');
    const translation = t(key);
    if (translation) {
      inp.placeholder = translation;
    }
  });
}

window.initI18n = initI18n;
window.setLanguage = setLanguage;
window.getCurrentLang = getCurrentLang;
window.t = t;
window.translations = translations;
