const LANG_KEY = "aischool_v2_lang";
let currentLang = localStorage.getItem(LANG_KEY) || "ru";

function t(key) {
  const dict = translations[currentLang] || translations.ru;
  return dict[key] !== undefined ? dict[key] : (translations.ru[key] !== undefined ? translations.ru[key] : key);
}

function getCurrentLang() {
  return currentLang;
}

function setLanguage(lang) {
  if (!translations[lang]) return;
  currentLang = lang;
  localStorage.setItem(LANG_KEY, lang);
  document.documentElement.lang = lang === "kz" ? "kk" : "ru";

  document.querySelectorAll("[data-i18n]").forEach(function (el) {
    const value = t(el.getAttribute("data-i18n"));
    if (value) el.textContent = value;
  });
  document.querySelectorAll("[data-i18n-placeholder]").forEach(function (el) {
    const value = t(el.getAttribute("data-i18n-placeholder"));
    if (value) el.setAttribute("placeholder", value);
  });
  document.querySelectorAll("[data-i18n-aria]").forEach(function (el) {
    const value = t(el.getAttribute("data-i18n-aria"));
    if (value) el.setAttribute("aria-label", value);
  });

  document.querySelectorAll(".lang-btn").forEach(function (btn) {
    const active = btn.dataset.lang === lang;
    btn.classList.toggle("is-active", active);
    btn.setAttribute("aria-pressed", String(active));
  });

  window.dispatchEvent(new CustomEvent("languageChanged", { detail: { lang: lang } }));
}

window.translations = translations;
window.t = t;
window.getCurrentLang = getCurrentLang;
window.setLanguage = setLanguage;
