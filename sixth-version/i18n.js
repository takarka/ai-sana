  t: function(key) {
    const langDict = this.translations[this.currentLang] || this.translations['ru'];
    return langDict[key] || this.translations['ru'][key] || key;
  },

  setLanguage: function(lang) {
    if (!this.translations[lang]) return;
    this.currentLang = lang;
    
    // Update all elements with data-i18n
    document.querySelectorAll('[data-i18n]').forEach(el => {
      const key = el.getAttribute('data-i18n');
      const text = this.t(key);
      if (text) {
        if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
          el.placeholder = text;
        } else {
          el.textContent = text;
        }
      }
    });

    // Update active state in language selector buttons
    document.querySelectorAll('.lang-btn').forEach(btn => {
      if (btn.getAttribute('data-lang') === lang) {
        btn.classList.add('active');
        btn.setAttribute('aria-pressed', 'true');
      } else {
        btn.classList.remove('active');
        btn.setAttribute('aria-pressed', 'false');
      }
    });

    // Update html lang attribute
    document.documentElement.lang = lang;
    
    // Dispatch custom event for dynamic components (calculator, dashboard, 3D mascot badges)
    window.dispatchEvent(new CustomEvent('aisana:langchange', { detail: { lang: lang } }));
  }
