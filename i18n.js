// Current language state
let currentLang = localStorage.getItem("pisa_lang") || "ru";

function setLanguage(lang) {
  if (!translations[lang]) return;
  currentLang = lang;
  localStorage.setItem("pisa_lang", lang);
  document.documentElement.lang = lang;

  // Update text nodes with data-i18n
  document.querySelectorAll("[data-i18n]").forEach(el => {
    const key = el.getAttribute("data-i18n");
    if (translations[lang] && translations[lang][key]) {
      el.textContent = translations[lang][key];
    }
  });

  // Update placeholder attributes with data-i18n-placeholder
  document.querySelectorAll("[data-i18n-placeholder]").forEach(el => {
    const key = el.getAttribute("data-i18n-placeholder");
    if (translations[lang] && translations[lang][key]) {
      el.setAttribute("placeholder", translations[lang][key]);
    }
  });

  // Update language switch buttons
  document.querySelectorAll(".lang-btn").forEach(btn => {
    if (btn.getAttribute("data-lang") === lang) {
      btn.classList.add("active");
    } else {
      btn.classList.remove("active");
    }
  });

  // Trigger custom event for components like charts or interactive tasks
  window.dispatchEvent(new CustomEvent("languageChanged", { detail: { lang } }));
}

window.translations = translations;
window.getCurrentLang = () => currentLang;
window.setLanguage = setLanguage;
